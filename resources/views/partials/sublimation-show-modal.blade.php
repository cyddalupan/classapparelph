        if (spVal > 0 && !spReason) { alert('Please provide a reason for the special price.'); return; }
        if (spVal > 0) {
            item.sublimationForm.specialPrice = { price: spVal, reason: spReason };
        }
    }
    
    // Submit
    var btn = document.getElementById('subAddItemBtn');
    btn.disabled = true;
    btn.innerHTML = '<i class="fas fa-spinner fa-spin me-2"></i> Adding...';
    
    fetch('{{ route("sales.prototype.add-product", $sale->id) }}', {
        method: 'POST',
        headers: {
            'Content-Type': 'application/json',
            'X-CSRF-TOKEN': document.querySelector('meta[name="csrf-token"]').content
        },
        body: JSON.stringify(item)
    })
    .then(function(r) { return r.json(); })
    .then(function(data) {
        if (data.success) {
            location.reload();
        } else {
            alert('Error: ' + (data.message || 'Unknown error'));
            btn.disabled = false;
            btn.innerHTML = '<i class="fas fa-check-circle me-2"></i> Add to Order';
        }
    })
    .catch(function(err) {
        alert('Network error: ' + err.message);
        btn.disabled = false;
        btn.innerHTML = '<i class="fas fa-check-circle me-2"></i> Add to Order';
    });
};

