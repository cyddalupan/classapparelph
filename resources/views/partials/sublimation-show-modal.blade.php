// ======= PRICE CALC =======
window.sub_calculateTotal = function() {
    var garmentSelect = document.getElementById('sub_garmentSelect');
    var fabricSelect = document.getElementById('sub_fabricSelect');
    var sizeInputs = document.querySelectorAll('.sub-size-qty');
    var rosterRows = document.querySelectorAll('#subRosterBody tr.roster-row');
    
    var garmentPrice = 0, fabricPrice = 0, partsPrice = 0, sizeAddon = 0;
    
    // Garment price
    if (garmentSelect.selectedIndex > 0) {
        garmentPrice = parseFloat(garmentSelect.options[garmentSelect.selectedIndex].dataset.price) || 0;
    }
    
    // Fabric price
    if (fabricSelect.selectedIndex > 0) {
        fabricPrice = parseFloat(fabricSelect.options[fabricSelect.selectedIndex].dataset.price) || 0;
    }
    
    // Parts
    document.querySelectorAll('#sub_partsContainer .part-checkbox:checked').forEach(function(cb) {
        partsPrice += parseFloat(cb.dataset.price) || 0;
    });
    
    // Sizes - count total qty and get size addons
    var totalQty = 0;
    var sizeBreakdownHtml = '';
    
    // Check which mode is active
    var isRoster = document.getElementById('subSizeModeRoster') && document.getElementById('subSizeModeRoster').checked;
    
    if (isRoster) {
        // Count roster rows
        rosterRows.forEach(function(row) {
            var qtyCell = row.querySelector('td:nth-child(4)');
            var qty = parseInt(qtyCell ? qtyCell.textContent : 1) || 1;
            totalQty += qty;
        });
    } else {
        sizeInputs.forEach(function(input) {
            var val = parseInt(input.value) || 0;
            if (val > 0) {
                var size = input.dataset.size;
                var sizePrice = window.sub_sizesData[size] || 0;
                sizeAddon += sizePrice * val;
                totalQty += val;
            }
        });
        
        // Show size breakdown
        var hasSizeDiff = false;
        sizeInputs.forEach(function(input) {
            var val = parseInt(input.value) || 0;
            if (val > 0) {
                var size = input.dataset.size;
                var sizePrice = window.sub_sizesData[size] || 0;
                if (sizePrice > 0) {
                    hasSizeDiff = true;
                    sizeBreakdownHtml += '<div class="d-flex justify-content-between small text-muted"><span>' + size + ' x' + val + '</span><span>+₱' + (sizePrice * val).toFixed(2) + '</span></div>';
                }
            }
        });
        if (hasSizeDiff) {
            sizeBreakdownHtml = '<hr class="my-1"><div class="small fw-bold text-muted">Size Add-ons:</div>' + sizeBreakdownHtml;
        }
    }
    
    var baseUnit = garmentPrice + fabricPrice + partsPrice;
    var maxSizeAddon = 0;
    if (!isRoster) {
        sizeInputs.forEach(function(input) {
            var size = input.dataset.size;
            var sizePrice = window.sub_sizesData[size] || 0;
            if (sizePrice > maxSizeAddon) maxSizeAddon = sizePrice;
        });
    }
    
    var unitPrice = baseUnit + maxSizeAddon;
    if (window.sub_hasSpecialPrice) {
        var spVal = parseFloat(document.getElementById('subSpecialPrintTotal').value) || 0;
        if (spVal > 0) unitPrice = spVal;
    }
    
    var grandTotal = unitPrice * totalQty;
    
    // Update UI
    document.getElementById('subPricing_garmentPrice').textContent = '₱' + garmentPrice.toFixed(2);
    document.getElementById('subPricing_fabricPrice').textContent = '₱' + fabricPrice.toFixed(2);
    
    var partsHtml = '';
    document.querySelectorAll('#sub_partsContainer .part-checkbox:checked').forEach(function(cb) {
        var label = cb.parentElement.querySelector('label');
        var price = parseFloat(cb.dataset.price) || 0;
        partsHtml += '<div class="d-flex justify-content-between small"><span>' + label.textContent + '</span><strong>+₱' + price.toFixed(2) + '</strong></div>';
    });
    if (partsHtml) {
        partsHtml = '<div class="d-flex justify-content-between small"><span>Parts:</span></div>' + partsHtml;
    }
    document.getElementById('subPricing_partsBreakdown').innerHTML = partsHtml;
    document.getElementById('subPricing_sizeBreakdown').innerHTML = sizeBreakdownHtml;
    document.getElementById('subPricing_unitPrice').textContent = '₱' + unitPrice.toFixed(2);
    document.getElementById('subPricing_totalQty').textContent = totalQty;
    document.getElementById('subPricing_grandTotal').textContent = '₱' + grandTotal.toFixed(2);
    
    // Update special price display
    if (window.sub_hasSpecialPrice) {
        document.getElementById('subSpecialPriceDisplay').textContent = '₱' + unitPrice.toFixed(2);
    }
};

